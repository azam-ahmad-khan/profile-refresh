#!/usr/bin/env bash
# Bundles SKILL.md and its references into one file for chat-only AIs (Custom GPT, Gemini Gem, Claude Project, etc.).
set -euo pipefail
cd "$(dirname "$0")/.."
skill=skills/profile-refresh
out=portable/profile-refresh-full.md
{
  echo "<!-- Generated by scripts/build-portable.sh from $skill. Edit the sources, not this file. -->"
  echo
  awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm' "$skill/SKILL.md"
  # Reading order for a chat AI; career-ops goes last because most people don't use it.
  for name in context-interview privacy confidentiality writing-guide linkedin-gotchas copy-paste-mode \
              resume ats-check tailor proof-of-work rerun career-ops; do
    f="$skill/references/$name.md"
    echo
    echo "---"
    echo
    echo "<!-- file: ${f#"$skill"/} -->"
    echo
    cat "$f"
  done
  echo
  echo "---"
  echo
  echo "<!-- file: templates/career-notes.md -->"
  echo
  cat "$skill/templates/career-notes.md"
} | sed -E 's#\[([^]]+)\]\((references/|templates/)?([a-z-]+\.md)\)#\1 (see the section marked file: \2\3)#g' > "$out"
echo "wrote $out ($(wc -l < "$out" | tr -d " ") lines)"
